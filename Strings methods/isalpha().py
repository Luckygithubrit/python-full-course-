# isalpha() is a string method in Python that returns True if all the characters in the string are alphabetic (letters) and there is at least one character, otherwise it returns False. If the string is empty or contains any non-alphabetic characters, it will return False.

# syntax is: string.isalpha()
a="lucky is good boy"
print(a.isalpha())

# ex2
b="luckyisgoodboy"
print(b.isalpha())#true

# ex3
c="lucky123"
print(c.isalpha())#false

