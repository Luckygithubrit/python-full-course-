# startswith() is a string method in Python that returns True if the string starts with the specified prefix, and False otherwise. It can also take optional start and end parameters to specify a range within the string to check for the prefix.

# syntax is: string.startswith(prefix[, start[, end]])

a="lucky is good boy"
print(a.startswith("lucky"))#True

print(a.startswith("good"))#False
