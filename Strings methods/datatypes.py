# datatypes is a module in Python that provides various functions and classes for working with different data types. It includes functions for converting between data types, checking the type of an object, and performing operations on data types. The module also provides classes for working with complex numbers, fractions, and decimal numbers.


#single valued datatypes

#int
a=2
print(type(a))#<class 'int'>

#float
b=2.5
print(type(b))#<class 'float'>

#complex
c=2+3j

print(type(c))#<class 'complex'>

#boolean
a=True
print(type(a))#<class 'bool'>
b=False
print(type(b))#<class 'bool'>
c=None
print(type(c))#<class 'NoneType'>


#address of the object

print(id(a))#140718353581208
print(id(b))#140718353581232
print(id(c))#140718353581264


