# endswith() is a string method in Python that returns True if the string ends with the specified suffix, and False otherwise. It can also take optional start and end parameters to specify a range within the string to check for the suffix.

# syntax is: string.endswith(suffix[, start[, end]])

a="lucky is good boy"
print(a.endswith("boy"))#True

print(a.endswith("good"))#False
