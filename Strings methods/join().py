# join() is a string method in Python that returns a string that is the concatenation of the strings in an iterable (e.g., list, tuple) separated by a specified separator string.

# syntax is: separator.join(iterable)


a=["lucky","is","good","boy"]
print(" ".join(a))#lucky is good boy

print("".join(a))#luckyisgoodboy
print("-".join(a))#lucky-is-good-boy

