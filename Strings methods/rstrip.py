# rstrip() is a string method in Python that returns a copy of the original string with trailing whitespace removed. It can also remove specified characters from the end of the string.


# syntax is: string.rstrip([chars])


a="   lucky is good boy   "
print(a.rstrip())#   lucky is good boy

